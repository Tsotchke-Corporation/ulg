export function createClosureTableSampleBuffer(samples, {
  axisKey = 'axis',
  outputKey = 'value',
  derivativeKey = 'derivative'
} = {}) {
  if (!Array.isArray(samples) || samples.length === 0) {
    throw new TypeError('samples must be a non-empty array');
  }
  const buffer = new Float32Array(samples.length * CLOSURE_TABLE_WGSL_SAMPLE_ROW_LAYOUT.length);
  samples.forEach((sample, index) => {
    const offset = index * CLOSURE_TABLE_WGSL_SAMPLE_ROW_LAYOUT.length;
    buffer[offset] = readSampleField(sample, [axisKey, 'axis', 'r', 'x'], `samples[${index}].axis`);
    buffer[offset + 1] = readSampleField(sample, [outputKey, 'value', 'energy'], `samples[${index}].value`);
    buffer[offset + 2] = derivativeAtSample(samples, index, axisKey, outputKey, derivativeKey);
    buffer[offset + 3] = 0;
  });
  return buffer;
}

function closureLawGraphOpId(op) {
  if (typeof op === 'number') return finiteNumber(op, 'node.opId');
  const id = CLOSURE_LAW_GRAPH_OP_IDS[op || 'tableLinear'];
  if (!id) throw new RangeError(`Unsupported closure law graph op: ${op}`);
  return id;
}

function closureLawGraphInterpolationId(interpolation) {
  if (typeof interpolation === 'number') return finiteNumber(interpolation, 'node.interpolationId');
  const id = CLOSURE_LAW_GRAPH_INTERPOLATION_IDS[interpolation || 'linear'];
  if (!id) throw new RangeError(`Unsupported closure law graph interpolation: ${interpolation}`);
  return id;
}

function readGraphIndex(value, label, fallback = 0) {
  const candidate = value == null ? fallback : Number(value);
  if (!Number.isInteger(candidate) || candidate < 0) {
    throw new TypeError(`${label} must be a non-negative integer`);
  }
  return candidate;
}

