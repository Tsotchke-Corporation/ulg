// Regenerates src/runtime/material/eshkolEosStiffnessTable.js: the
// dimensionless bulk stiffness K / (rho0 c^2) of each packed liquid EOS as a
// function of x = rho / rho0, derived by Eshkol automatic differentiation in
// the client-side warm VM worker (A6) and fitted as an A4 Chebyshev response
// (held-out residuals). The GPU semi-implicit pressure solve evaluates this
// table (sphImplicitPressureGpu.js); tests/eshkolEosStiffnessTable.native.test.mjs
// re-derives it and checks the cached coefficients.
//   node scripts/derive-eshkol-eos-stiffness-table.mjs   (HTTPS dev server on 5173)
import { chromium } from '@playwright/test';
import { writeFile } from 'node:fs/promises';

export async function deriveDimensionlessTaitStiffness(baseUrl = 'https://127.0.0.1:5173/') {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true,
    args: ['--use-angle=vulkan', '--enable-features=Vulkan,UseSkiaRenderer', '--enable-unsafe-webgpu', '--ignore-gpu-blocklist'] });
  try {
    const page = await browser.newPage({ ignoreHTTPSErrors: true });
    await page.goto(baseUrl, { waitUntil: 'domcontentloaded', timeout: 60000 });
    return await page.evaluate(async () => {
      const { deriveEosStiffnessResponse, ESHKOL_EOS_MODEL } = await import('/src/runtime/material/eshkolEosStiffness.js');
      const worker = new Worker('/workers/eshkol-warm-vm.worker.js');
      let nextId = 1;
      const sample = (definition, call, points) => new Promise((resolve, reject) => {
        const id = nextId++;
        const onMessage = (event) => {
          if (event.data?.id !== id) return;
          worker.removeEventListener('message', onMessage);
          if (event.data.ok) resolve(event.data.samples); else reject(new Error(event.data.error));
        };
        worker.addEventListener('message', onMessage);
        worker.postMessage({ id, type: 'sample', definition, call, points });
      });
      try {
        // rho0 = c = 1: K(x) / (rho0 c^2) over x = rho / rho0 in [0.9, 1.1]
        // (liquid J is clamped to [0.95, 1.05], so x stays inside).
        const d = await deriveEosStiffnessResponse({ sample, eosModel: ESHKOL_EOS_MODEL.TAIT, restDensityKgPerM3: 1,
          soundSpeedMPerS: 1, densityRange: [0.9, 1.1], degree: 10, relativeTolerance: 1e-9 });
        return { coefficients: Array.from(d.responseFunction.coefficients), domain: [d.responseFunction.axes[0].lo,
          d.responseFunction.axes[0].hi], degree: d.responseFunction.axes[0].degree,
        relativeBound: d.responseFunction.residuals.relativeBound, crossCheck: d.crossCheckMaxRelativeError,
        sampleCount: d.sampleCount, program: d.program };
      } finally {
        worker.terminate();
      }
    });
  } finally {
    await browser.close();
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const tait = await deriveDimensionlessTaitStiffness();
  const body = `// GENERATED by scripts/derive-eshkol-eos-stiffness-table.mjs: do not edit.
// Dimensionless bulk stiffness K / (rho0 c^2) of the packed Tait liquid EOS
// (gamma 7) over x = rho / rho0, derived by Eshkol automatic differentiation
// (eos-stiffness = rho * (derivative eos-pressure rho)) and fitted as an A4
// Chebyshev response (first-kind nodes, held-out residual bound below).
// Evaluate with Clenshaw at t = 2 (x - lo) / (hi - lo) - 1.
export const ESHKOL_TAIT_STIFFNESS_TABLE = Object.freeze({
  schema: 'peercompute.ulg.eshkol-eos-stiffness-table.v1',
  eosModel: 1,
  quantity: 'K / (rho0 c^2) as a function of rho / rho0',
  domain: Object.freeze(${JSON.stringify(tait.domain)}),
  degree: ${tait.degree},
  coefficients: Object.freeze(${JSON.stringify(tait.coefficients)}),
  relativeResidualBound: ${tait.relativeBound},
  eshkolCrossCheckMaxRelativeError: ${tait.crossCheck},
  sampleCount: ${tait.sampleCount},
  eshkolProgram: Object.freeze(${JSON.stringify(tait.program)})
});
`;
  await writeFile(new URL('../src/runtime/material/eshkolEosStiffnessTable.js', import.meta.url), body);
  console.log(JSON.stringify({ written: 'src/runtime/material/eshkolEosStiffnessTable.js', ...tait, program: undefined }));
}
